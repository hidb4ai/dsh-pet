#!/usr/bin/env node
/**
 * Build the shared layer (src/shared) into the classic script of the desktop Helper:
 * runtime/electron-helper/shared-core.js, and hang it on the global window.PetShared. Must be classic script and not
 * ESM: desktop Helper loads pages from file://, Chromium has CORS restrictions on ES from file:// and module.
 * shared-core.js is loaded before renderer.js, and renderer directly reads the global data without building another
 * module system. Only this build output is produced without type checking or declaration; it is called by npm run
 * build:desktop-core in the release chain.
 * @module dsh-pet/scripts/build-desktop-core
 */
import { rolldown } from 'rolldown';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'runtime', 'electron-helper', 'shared-core.js');

try {
  const bundle = await rolldown({
    input: join(ROOT, 'src', 'shared', 'index.ts'),
    platform: 'browser',
  });
  await bundle.write({
    format: 'iife',
    name: 'PetShared',
    file: OUT,
  });
  // The product is submitted to the warehouse and loaded from file:// by Helper: The file header must declare the generation source to avoid being silently overwritten by the build after being manually modified.
  const banner = [
    '/**',
    ' * @generated by `npm run build:desktop-core` (scripts/build-desktop-core.mjs). Do not edit by hand.',
    ' * Source: src/shared/index.ts.',
    ' */',
  ].join('\n');
  const code = readFileSync(OUT, 'utf8');
  if (!code.startsWith('/**')) writeFileSync(OUT, banner + '\n' + code);
  console.log('[build-desktop-core] ✓ runtime/electron-helper/shared-core.js (window.PetShared)');
} catch (error) {
  console.error('[build-desktop-core] build failed:', error);
  process.exit(1);
}
