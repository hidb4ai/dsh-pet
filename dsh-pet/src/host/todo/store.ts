/**
 * To-do persistence: Read and atomic write of a single JSON file, all operations are serialized in the same queue.
 *
 * It is not responsible for verifying the HTTP input (returned to ../routes/todos) and the reminder rhythm (returned
 * to ./policy). The cache is just a copy of the disk: it is replaced every time persist to disk succeeds, so the
 * half-written state cannot be read. If any step fails, it will be thrown as it is and will be converted into an
 * internal error by route; the user's to-do list will not be silently discarded.
 * @module dsh-pet/src/host/todo/store
 */
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { cloneTodo, parseTodoFile, sortTodos, TODO_FILE_VERSION, type TodoFile, type TodoRecord } from './types.ts';
import type { LoggerLike } from '../log-file.ts';

/** To-do file name: It falls in the plugin user data directory; the host database creation and setting page display path share this one. */
export const TODO_FILE_NAME = 'todos.json';

/** Fields updated once: Keys that do not appear remain unchanged. */
export interface TodoPatch {
  text?: string;
  dueAt?: number | null;
  done?: boolean;
}

/** Construct input parameters. */
export interface TodoStoreOptions {
  /** Absolute path of to-do file (automatically created when the parent directory does not exist). */
  file: string;
  /** Warning outlet for failure in reading and writing disk. */
  log: LoggerLike;
  /** Time source; test injects a fixed clock. */
  now?: () => number;
}

/** Exception → one line of readable reason (for log purposes, not leaked to HTTP response). */
function messageOf(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

export class TodoStore {
  declare private readonly file: string;
  declare private readonly log: LoggerLike;
  declare private readonly now: () => number;
  /** Serial queue: All reads and writes are queued to avoid interleaving of reads, modifications and writes. */
  declare private queue: Promise<void>;
  /** In-process copy of disk contents; null = Not read yet. */
  declare private cached: TodoRecord[] | null;
  /** The sequence number when multiple entries are built in the same millisecond. */
  declare private seq: number;

  constructor(options: TodoStoreOptions) {
    this.file = options.file;
    this.log = options.log;
    this.now = options.now ?? (() => Date.now());
    this.queue = Promise.resolve();
    this.cached = null;
    this.seq = 0;
  }

  /** All to-dos (sorted copies). */
  list(): Promise<TodoRecord[]> {
    return this.run(async () => {
      await this.ensureLoaded();
      return sortTodos(this.cached ?? []).map(cloneTodo);
    });
  }

  /**
   * Create a new one.
   *
   * id is generated by timestamp + in-process sequence number: the timestamp is different after restarting, and the
   * old id will not collide.
   *
   * @param input - Verified text and expiration time.
   * @returns record copy after persist to disk success.
   */
  create(input: { text: string; dueAt: number | null }): Promise<TodoRecord> {
    return this.run(async () => {
      await this.ensureLoaded();
      const at = this.now();
      this.seq += 1;
      const todo: TodoRecord = {
        id: `todo-${at.toString(36)}-${this.seq.toString(36)}`,
        text: input.text,
        dueAt: input.dueAt,
        done: false,
        createdAt: at,
        updatedAt: at,
        completedAt: null,
        lastRemindedAt: null,
      };
      await this.persist([...(this.cached ?? []), todo]);
      return cloneTodo(todo);
    });
  }

  /**
   * Update one item.
   *
   * Changing the expiration date or reopening will clear `lastRemindedAt` : a reminder to reschedule based on the new
   * expiration time.
   *
   * @returns updated record; if id does not exist return null.
   */
  update(id: string, patch: TodoPatch): Promise<TodoRecord | null> {
    return this.run(async () => {
      await this.ensureLoaded();
      const list = this.cached ?? [];
      const index = list.findIndex((todo) => todo.id === id);
      if (index < 0) return null;
      const prev = list[index]!;
      const at = this.now();
      const next: TodoRecord = { ...prev, updatedAt: at };
      if (patch.text !== undefined) next.text = patch.text;
      if (patch.dueAt !== undefined) {
        next.dueAt = patch.dueAt;
        next.lastRemindedAt = null;
      }
      if (patch.done !== undefined) {
        next.done = patch.done;
        next.completedAt = patch.done ? (prev.completedAt ?? at) : null;
        if (!patch.done) next.lastRemindedAt = null;
      }
      const updated = [...list];
      updated[index] = next;
      await this.persist(updated);
      return cloneTodo(next);
    });
  }

  /**
   * Delete an item.
   *
   * @returns The number of deleted items; 0 means there is none (idempotent, not considered an error).
   */
  remove(id: string): Promise<number> {
    return this.run(async () => {
      await this.ensureLoaded();
      const list = this.cached ?? [];
      const next = list.filter((todo) => todo.id !== id);
      if (next.length === list.length) return 0;
      await this.persist(next);
      return 1;
    });
  }

  /** Write down a reminder: only move `lastRemindedAt`, do not advance `updatedAt` (that is not user modification). */
  markReminded(id: string, at: number): Promise<void> {
    return this.run(async () => {
      await this.ensureLoaded();
      const list = this.cached ?? [];
      const index = list.findIndex((todo) => todo.id === id);
      if (index < 0) return;
      const next = [...list];
      next[index] = { ...list[index]!, lastRemindedAt: at };
      await this.persist(next);
    });
  }

  /** Queue: Execute the next task after the previous task ends; failure does not affect subsequent tasks. */
  private run<T>(task: () => Promise<T>): Promise<T> {
    const next = this.queue.then(task, task);
    this.queue = next.then(
      () => undefined,
      () => undefined,
    );
    return next;
  }

  private async ensureLoaded(): Promise<void> {
    if (this.cached !== null) return;
    this.cached = await this.readDisk();
  }

  private async readDisk(): Promise<TodoRecord[]> {
    let raw: string;
    try {
      raw = await readFile(this.file, 'utf8');
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') {
        this.log.warn?.(`[dsh-pet] Could not read the to-do file; continuing with an empty list: ${messageOf(error)}`);
      }
      return [];
    }
    try {
      return parseTodoFile(JSON.parse(raw));
    } catch (error) {
      // Bad files are not backed up or rewritten: first run according to the empty list, and the next write will naturally overwrite it.
      this.log.warn?.(`[dsh-pet] Could not parse the to-do file; continuing with an empty list: ${messageOf(error)}`);
      return [];
    }
  }

  /** Atomic write: rename is written after the temporary file is written, and half of JSON will not be left when the process exits midway. */
  private async persist(next: readonly TodoRecord[]): Promise<void> {
    const file: TodoFile = { version: TODO_FILE_VERSION, todos: [...next] };
    await mkdir(dirname(this.file), { recursive: true });
    const temp = this.file + '.tmp';
    await writeFile(temp, JSON.stringify(file, null, 2) + '\n', 'utf8');
    await rename(temp, this.file);
    this.cached = [...next];
  }
}
