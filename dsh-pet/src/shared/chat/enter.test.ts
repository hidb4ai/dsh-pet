/**
 * Contract test of carriage return processing determination: which carriage return is sent, which time only the
 * default behavior is blocked, and which time it is not touched at all. Running method: node --
 * experimental-strip-types --test src/shared/chat/enter.test.ts
 */
import { describe, test } from 'node:test';
import assert from 'node:assert/strict';

import { COMPOSITION_SETTLE_MS, createCompositionWatch, decideEnter } from './enter.ts';
import type { EnterKeyEvent } from './enter.ts';

/** Create a button; only fill in the fields that are of concern. */
function key(overrides: Partial<EnterKeyEvent> = {}): EnterKeyEvent {
  return { key: 'Enter', shiftKey: false, ...overrides };
}

describe('decideEnter', () => {
  test('Normal Enter → Send', () => {
    assert.equal(decideEnter(key(), createCompositionWatch(), 0), 'send');
  });

  test('Shift + Enter → No intervention (leave for line breaks)', () => {
    assert.equal(decideEnter(key({ shiftKey: true }), createCompositionWatch(), 0), 'ignore');
  });

  test('Enter in combination (isComposing) → No intervention (leave it to the input method to display the screen)', () => {
    assert.equal(decideEnter(key({ isComposing: true }), createCompositionWatch(), 0), 'ignore');
  });

  test('keyCode 229 (Input method key swallowing) → No intervention', () => {
    assert.equal(decideEnter(key({ keyCode: 229 }), createCompositionWatch(), 0), 'ignore');
  });

  test('The combination is not over yet (watch is in the combination) → No intervention', () => {
    const watch = createCompositionWatch();
    watch.start();
    assert.equal(decideEnter(key(), watch, 0), 'ignore');
  });

  test('Long press and press Enter in the combination → still no intervention (return to input method)', () => {
    const watch = createCompositionWatch();
    watch.start();
    assert.equal(decideEnter(key({ isComposing: true, repeat: true }), watch, 0), 'ignore');
  });

  test('Repeated carriage returns generated by long pressing → block but not send (otherwise it will keep changing lines)', () => {
    assert.equal(decideEnter(key({ repeat: true }), createCompositionWatch(), 0), 'swallow');
  });

  test('Just after the combination: only intercept within the silent window, and send after exiting the window', () => {
    const watch = createCompositionWatch();
    watch.start();
    watch.end(1000);
    assert.equal(
      decideEnter(key(), watch, 1000),
      'swallow',
      'It should not be sent when the screen appears, and do not insert blank lines.',
    );
    assert.equal(decideEnter(key(), watch, 1000 + COMPOSITION_SETTLE_MS - 1), 'swallow', 'Still blocked in the window');
    assert.equal(
      decideEnter(key(), watch, 1000 + COMPOSITION_SETTLE_MS),
      'send',
      'Normal sending resumes after exiting the silent window',
    );
  });

  test('Non-Enter key → No intervention', () => {
    assert.equal(decideEnter(key({ key: 'a' }), createCompositionWatch(), 0), 'ignore');
  });
});

describe('createCompositionWatch', () => {
  test('start / end maintenance combination state and end time', () => {
    const watch = createCompositionWatch();
    assert.equal(watch.isComposing(), false, 'Not in the combination initially');
    watch.start();
    assert.equal(watch.isComposing(), true);
    watch.end(500);
    assert.equal(watch.isComposing(), false);
    assert.equal(watch.endedWithin(500), true);
  });

  test('Combination never ended → never in silent window', () => {
    const watch = createCompositionWatch();
    assert.equal(watch.endedWithin(0), false);
    assert.equal(watch.endedWithin(Number.MAX_SAFE_INTEGER), false);
  });
});
