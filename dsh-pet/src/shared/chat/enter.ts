/**
 * Criteria for "Press Enter to send" in the dialog input box: it is sent only when Enter is pressed and the input
 * method does not control this key. The desktop side is shared with the browser side; the combined state is
 * transferred from compositionstart / compositionend. This module does not touch DOM and does not read the clock.
 * @module dsh-pet/src/shared/chat/enter
 */

/** After the combination is completed, the silent window (ms) is still counted as "on screen": Safari will be distributed first compositionend and then keydown. */
export const COMPOSITION_SETTLE_MS = 80;

/** Determine the keyboard field to be read; native KeyboardEvent and ordinary objects in the test can be passed directly. */
export interface EnterKeyEvent {
  readonly key: string;
  readonly shiftKey: boolean;
  /** The keys pressed in the combination: Chromium and Safari are labeled true. */
  readonly isComposing?: boolean;
  /** The old flag when input method swallows keys (Windows). */
  readonly keyCode?: number;
  /** Automatic repeat generated by long press. */
  readonly repeat?: boolean;
}

/** The input method combination state of an input box; the holder is responsible for transferring the two combination events. */
export interface CompositionWatch {
  /** compositionstart: Enter the combination. */
  readonly start: () => void;
  /** compositionend: Record the end time. */
  readonly end: (at: number) => void;
  /** Is it being combined at this moment? */
  readonly isComposing: () => boolean;
  /** Have you just finished the combination and are you still in the silent window? */
  readonly endedWithin: (now: number) => boolean;
}

/**
 * How to handle a carriage return.
 *
 * Neither `swallow` nor `ignore` is sent. The difference lies in the default behavior of blocking or not blocking: the
 * former is "this enter is useless" (long press to repeat, the screen is up), blocking it will not be regarded as a
 * line break; the latter is "this key has another owner" (combined, Shift + enter).
 */
export type EnterAction = 'send' | 'swallow' | 'ignore';

/**
 * Create an empty combination state.
 *
 * @returns is a handle shared by `compositionstart` / `compositionend` and {@link decideEnter} .
 */
export function createCompositionWatch(): CompositionWatch {
  let composing = false;
  // Use - Infinity when "never ended": the silent window judgment at any time is false, no additional branches are needed
  let endedAt = Number.NEGATIVE_INFINITY;
  return {
    start: () => {
      composing = true;
    },
    end: (at) => {
      composing = false;
      endedAt = at;
    },
    isComposing: () => composing,
    endedWithin: (now) => now - endedAt < COMPOSITION_SETTLE_MS,
  };
}

/**
 * Who owns the carriage return this time?
 *
 * @param event - Fields related to input methods in keyboard events.
 * @param watch - the combined state of this input box.
 * @param now - The current time ( ms ) must use the same clock as {@link CompositionWatch.end} .
 * @returns `send` sends; `swallow` blocks the default behavior but does not send; `ignore` does not intervene (the
 * input method or line wrapping is handled by itself).
 */
export function decideEnter(event: EnterKeyEvent, watch: CompositionWatch, now: number): EnterAction {
  if (event.key !== 'Enter' || event.shiftKey) return 'ignore';
  // The Enter Return input method in the combination: At this time, preventDefault may interrupt the screen without even blocking it.
  if (event.isComposing === true || event.keyCode === 229 || watch.isComposing()) return 'ignore';
  // Repeated carriage returns generated by long pressing: neither should be sent, nor should a line feed be inserted every time
  if (event.repeat === true) return 'swallow';
  // When the screen first appears: the combination has been submitted. To stop the default behavior, just don’t leave a blank line.
  if (watch.endedWithin(now)) return 'swallow';
  return 'send';
}
