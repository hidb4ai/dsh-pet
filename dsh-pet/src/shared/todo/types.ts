/**
 * The shape and analysis of pending wire: the panel only consumes the data returned by host / todos.
 *
 * No fetching and rendering are performed; the field conventions have the same name as host/todo/types (host and
 * import share the layer, and the two copies are maintained separately). The host has been verified and sorted, and
 * the type is narrowed again: dirty data is skipped instead of failing to render the entire list.
 * @module dsh-pet/src/shared/todo/types
 */

/** A to-do (the minimum field required for panel display). */
export interface TodoItem {
  /** Instance identifier generated by host; path segment of PATCH / DELETE. */
  id: string;
  text: string;
  /** Expiration time (epoch ms); null = no expiry. */
  dueAt: number | null;
  done: boolean;
  createdAt: number;
  updatedAt: number;
  /** Completion time; unfinished is null. */
  completedAt: number | null;
}

/** Reading a number, invalid fallback. */
function numberOr(raw: unknown, fallback: number): number {
  return typeof raw === 'number' && Number.isFinite(raw) ? raw : fallback;
}

/**
 * Narrow one to-do list.
 *
 * @param raw - a single item in the response body.
 * @returns returns the record when it is valid; id / when the text is missing or dueAt is of the wrong type, null is
 * returned.
 */
export function parseTodoItem(raw: unknown): TodoItem | null {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null;
  const record = raw as Record<string, unknown>;
  if (typeof record.id !== 'string' || record.id === '') return null;
  if (typeof record.text !== 'string') return null;
  const dueAt =
    record.dueAt === null || record.dueAt === undefined
      ? null
      : typeof record.dueAt === 'number' && Number.isFinite(record.dueAt)
        ? record.dueAt
        : undefined;
  if (dueAt === undefined) return null;
  return {
    id: record.id,
    text: record.text,
    dueAt,
    done: record.done === true,
    createdAt: numberOr(record.createdAt, 0),
    updatedAt: numberOr(record.updatedAt, 0),
    completedAt: typeof record.completedAt === 'number' ? record.completedAt : null,
  };
}

/**
 * Narrow the entire list: Instead of treating the array as an empty list, bad entries are skipped one by one.
 *
 * @param raw - `todos` field in the response body.
 * @returns Checked list (keep original order).
 */
export function parseTodoList(raw: unknown): TodoItem[] {
  if (!Array.isArray(raw)) return [];
  const out: TodoItem[] = [];
  for (const item of raw) {
    const todo = parseTodoItem(item);
    if (todo !== null) out.push(todo);
  }
  return out;
}

/**
 * Display order: unfinished first (the closer the due date is to the front, unlimited time at the bottom), completed
 * last (the most recently completed one is at the top).
 *
 * The host has also been sorted once; here it is sorted again to ensure that the order is not distorted when "a single
 * PATCH response is directly inserted into the list".
 *
 * @param list - A list in any order.
 * @returns New sorted array.
 */
export function sortTodoItems(list: readonly TodoItem[]): TodoItem[] {
  return [...list].sort((a, b) => {
    if (a.done !== b.done) return a.done ? 1 : -1;
    if (a.done) return (b.completedAt ?? 0) - (a.completedAt ?? 0);
    const aDue = a.dueAt ?? Number.POSITIVE_INFINITY;
    const bDue = b.dueAt ?? Number.POSITIVE_INFINITY;
    if (aDue !== bDue) return aDue - bDue;
    return a.createdAt - b.createdAt;
  });
}
